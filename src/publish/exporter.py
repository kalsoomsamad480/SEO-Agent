"""Save a finished blog to outputs/blogs/<slug>/.

Files written:
    post.md                 the article, with a settings block on top
                            (so `python main.py validate --file .../post.md` works on it)
    post.html               a complete web page: title tag, meta description,
                            canonical link, and structured data (JSON-LD)
    meta.json               title, meta description, slug, keywords, image info
    validation_report.json  the pass/fail result of every SEO rule

Structured data (JSON-LD) is a hidden block that tells Google and AI answer
engines "this is an article" and "these are FAQ questions with answers".
It is one of the cheapest ways to help a page show up in rich results.
"""

import html
import json
from pathlib import Path

import markdown

import config
from src.models.schemas import BlogDraft, ValidationReport
from src.utils import text_tools as tt
from src.utils.logger import get_logger

logger = get_logger(__name__)

# Small, readable default styling. Your CMS theme will replace it when you publish.
PAGE_STYLE = """
  body { font-family: system-ui, sans-serif; max-width: 760px; margin: 2rem auto;
         padding: 0 1rem; line-height: 1.7; color: #222; }
  img { max-width: 100%; height: auto; }
  pre { background: #f4f4f4; padding: 1rem; overflow-x: auto; }
  .review-note { background: #fff4ce; padding: .75rem 1rem; border-radius: 6px; }
"""


def build_front_matter(draft: BlogDraft) -> str:
    """Write the draft's settings as a '---' block that split_front_matter can read back."""
    fields = {
        "title": draft.title,
        "meta_description": draft.meta_description,
        "slug": draft.slug,
        "focus_keyword": draft.focus_keyword,
        "secondary_keywords": ", ".join(draft.secondary_keywords),
        "feature_image_alt": draft.feature_image_alt,
        "feature_image_url": draft.feature_image_url,
        "audience": draft.audience,
        "site_url": draft.site_url,
        "main_page_url": draft.main_page_url or "",
        "child_page_urls": ", ".join(draft.child_page_urls),
    }
    lines = [f"{key}: {value}" for key, value in fields.items() if value]
    return "---\n" + "\n".join(lines) + "\n---\n"


def build_structured_data(draft: BlogDraft) -> list[dict]:
    """JSON-LD for the article and (if present) its FAQ section."""
    # Imported here because seo_rules imports a lot; only needed for HTML export.
    from src.validators.seo_rules import get_faq_questions

    data: list[dict] = [{
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": draft.title,
        "description": draft.meta_description,
        "image": draft.feature_image_url,
        "keywords": ", ".join([draft.focus_keyword, *draft.secondary_keywords]),
    }]
    questions = get_faq_questions(draft) or []
    if questions:
        data.append({
            "@context": "https://schema.org",
            "@type": "FAQPage",
            "mainEntity": [{
                "@type": "Question",
                "name": q.title,
                "acceptedAnswer": {"@type": "Answer",
                                   "text": tt.markdown_to_plain_text(q.content).strip()},
            } for q in questions],
        })
    return data


def build_html(draft: BlogDraft) -> str:
    """Turn the draft into a complete, standalone HTML page."""
    # "extra" adds tables, fenced code blocks and other common Markdown features.
    article_html = markdown.markdown(draft.body_markdown, extensions=["extra"])
    canonical = ""
    if draft.site_url:
        canonical = f'  <link rel="canonical" href="{html.escape(draft.site_url)}/{draft.slug}/">\n'
    json_ld = "\n".join(
        f'  <script type="application/ld+json">\n{json.dumps(block, indent=2)}\n  </script>'
        for block in build_structured_data(draft)
    )
    # html.escape stops characters like " or < in a title from breaking the page.
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{html.escape(draft.title)}</title>
  <meta name="description" content="{html.escape(draft.meta_description)}">
{canonical}{json_ld}
  <style>{PAGE_STYLE}</style>
</head>
<body>
  <p class="review-note">Draft generated by SEO Agent. Human review required before publishing.</p>
{article_html}
</body>
</html>
"""


def save_blog(draft: BlogDraft, report: ValidationReport) -> Path:
    """Save all four files; return the folder they were saved in."""
    folder = config.BLOGS_DIR / draft.slug
    folder.mkdir(parents=True, exist_ok=True)

    (folder / "post.md").write_text(build_front_matter(draft) + draft.body_markdown, encoding="utf-8")
    (folder / "post.html").write_text(build_html(draft), encoding="utf-8")

    meta = draft.model_dump(exclude={"body_markdown"})
    (folder / "meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    # mode="json" turns dates into text so they can be saved as JSON.
    report_data = report.model_dump(mode="json")
    report_data["passed"] = report.passed
    report_data["score"] = report.score
    (folder / "validation_report.json").write_text(json.dumps(report_data, indent=2), encoding="utf-8")

    logger.info("Saved blog to %s", folder)
    return folder
